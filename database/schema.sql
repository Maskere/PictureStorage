CREATE TABLE IF NOT EXISTS pictures (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename text NOT NULL,
    file_path text NOT NULL,
    uploaded_at timestamp with time zone DEFAULT now(),
    captured_at timestamp with time zone NULL,
    capture_date_checked boolean NOT NULL DEFAULT false
);

ALTER TABLE pictures ADD COLUMN IF NOT EXISTS captured_at timestamp with time zone NULL;
ALTER TABLE pictures ADD COLUMN IF NOT EXISTS capture_date_checked boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS ix_pictures_filename
    ON pictures (filename);
